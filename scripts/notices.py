"""Write THIRD-PARTY-NOTICES: the licences of the crates (and C libzstd)
compiled into the wasm module, from each crate's own licence file (and
NOTICE file, for Apache-2.0 crates that have one) in cargo's registry.
Run after the crates change:

    python3 scripts/notices.py

It reads the crate list from `cargo tree` for the wasm target, so the
crates must have been fetched (any cargo build does that). Adapted from
dta-parser's scripts/js-notices.py.
"""

import glob
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Where a crate offers a choice, the licence the notices carry, by file.
PREFER = ["LICENSE-MIT", "LICENSE-MIT.md", "LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "LICENSE-APACHE", "LICENSE-APACHE.txt"]


def crates():
    out = subprocess.run(
        ["cargo", "tree", "--target", "wasm32-unknown-unknown", "-e", "normal,no-proc-macro", "--prefix", "none"],
        cwd=ROOT, check=True, capture_output=True, text=True).stdout
    seen = set()
    for line in out.splitlines():
        m = re.match(r"(\S+) v(\S+)( \(.*\))?", line)
        if m and not m.group(3):
            seen.add((m.group(1), m.group(2)))
    return sorted(seen)


def source(name, version):
    home = os.environ.get("CARGO_HOME", os.path.expanduser("~/.cargo"))
    found = glob.glob(f"{home}/registry/src/*/{name}-{version}")
    if not found:
        raise SystemExit(f"{name} {version} is not in cargo's registry; run a cargo build first")
    return Path(found[0])


def field(toml, key):
    m = re.search(rf'^{key}\s*=\s*"([^"]*)"', toml, re.M)
    return m.group(1) if m else ""


def main():
    parts = ["Third-party notices for pqparser\n\n"
             "The WebAssembly module is built from this repository's Rust code\n"
             "(GPL-3.0-only; see LICENSE) and these crates from crates.io, with their\n"
             "licences below. Generated by scripts/notices.py.\n"]
    found = crates()
    versions = dict(found)
    for name, version in found:
        d = source(name, version)
        toml = (d / "Cargo.toml").read_text()
        text = next(((d / f).read_text() for f in PREFER if (d / f).is_file()), None)
        if text is None and field(toml, "license") == "Apache-2.0":
            # flatbuffers ships no licence file: the licence's text, from arrow-schema's copy.
            text = "(The crate's package has no licence file; this is the Apache License 2.0 it names.)\n\n"
            text += (source("arrow-schema", versions["arrow-schema"]) / "LICENSE.txt").read_text()
        if text is None:
            raise SystemExit(f"{name}: no licence file found")
        parts.append(f"\n{'=' * 72}\n{name} {version} ({field(toml, 'license')})\n{field(toml, 'repository')}\n{'=' * 72}\n\n{text.strip()}\n")
        for notice in ["NOTICE.txt", "NOTICE"]:
            if (d / notice).is_file():
                parts.append(f"\n{'-' * 72}\n{name}'s {notice}\n{'-' * 72}\n\n{(d / notice).read_text().strip()}\n")
                break
        if name == "zstd-sys":
            parts.append(f"\n{'-' * 72}\nZstandard (libzstd), compiled in by zstd-sys (BSD-3-Clause, chosen\nfrom BSD or GPLv2)\nhttps://github.com/facebook/zstd\n{'-' * 72}\n\n{(d / 'zstd' / 'LICENSE').read_text().strip()}\n")
    (ROOT / "THIRD-PARTY-NOTICES").write_text("".join(parts))


if __name__ == "__main__":
    main()
